-- Sahar: real microphone clips in a room, who is speaking, and a host mute that
-- blocks audio server-side (not just in the interface).

alter table public.room_seats add column if not exists speaking boolean not null default false;

create table if not exists public.room_voices (
  id bigint generated by default as identity primary key,
  room_id uuid not null references public.rooms (id) on delete cascade,
  user_id uuid references auth.users (id) on delete set null,
  author text not null check (char_length(author) between 1 and 32),
  storage_path text not null,
  duration_ms integer not null default 0 check (duration_ms between 0 and 30000),
  created_at timestamptz not null default now()
);

create index if not exists room_voices_room_created_idx on public.room_voices (room_id, created_at desc, id desc);

alter table public.room_voices enable row level security;

drop policy if exists voices_read on public.room_voices;
create policy voices_read on public.room_voices for select to anon, authenticated using (true);

-- Only a member sitting in this room and not muted may upload a clip.
drop policy if exists room_voice_insert on storage.objects;
create policy room_voice_insert on storage.objects
  for insert to anon, authenticated
  with check (
    bucket_id = 'room-voice'
    and (storage.foldername(name))[2] = auth.uid()::text
    and exists (
      select 1 from public.room_seats s
      where s.room_id::text = (storage.foldername(name))[1]
        and s.user_id = auth.uid()
        and s.muted = false
    )
  );

drop policy if exists room_voice_read on storage.objects;
create policy room_voice_read on storage.objects
  for select to anon, authenticated
  using (bucket_id = 'room-voice');

drop policy if exists room_voice_delete_own on storage.objects;
create policy room_voice_delete_own on storage.objects
  for delete to authenticated
  using (bucket_id = 'room-voice' and (storage.foldername(name))[2] = auth.uid()::text);

create or replace function public.set_speaking(p_room uuid, p_speaking boolean)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then raise exception 'Inicia sesión'; end if;
  update public.room_seats
  set speaking = (p_speaking and not muted)
  where room_id = p_room and user_id = auth.uid();
end;
$$;

create or replace function public.publish_voice(p_room uuid, p_path text, p_duration integer default 0)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  seat public.room_seats;
  new_id bigint;
  speaker text;
begin
  if uid is null then raise exception 'Inicia sesión para hablar'; end if;
  select * into seat from public.room_seats where room_id = p_room and user_id = uid;
  if seat.user_id is null then raise exception 'Siéntate en un asiento para hablar'; end if;
  if seat.muted then raise exception 'El anfitrión te ha silenciado'; end if;
  if p_path not like p_room::text || '/' || uid::text || '/%' then raise exception 'Ruta de audio no válida'; end if;
  speaker := seat.display_name;
  insert into public.room_voices (room_id, user_id, author, storage_path, duration_ms)
  values (p_room, uid, speaker, p_path, greatest(0, least(30000, coalesce(p_duration, 0))))
  returning id into new_id;
  update public.room_seats set speaking = false where room_id = p_room and user_id = uid;
  delete from public.room_voices
  where room_id = p_room
    and id in (
      select id from public.room_voices
      where room_id = p_room
      order by created_at desc, id desc
      offset 60
    );
  return new_id;
end;
$$;

-- Muting cuts the person's microphone state immediately, not only their next clip.
create or replace function public.moderate_member(p_room uuid, p_user uuid, p_action text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  target text;
begin
  if not public.room_is_host(p_room) then raise exception 'Solo el anfitrión puede moderar'; end if;
  if p_user = auth.uid() then raise exception 'No puedes moderarte a ti mismo'; end if;
  select display_name into target from public.room_seats where room_id = p_room and user_id = p_user;
  if target is null then raise exception 'Esa persona ya no está en la sala'; end if;
  if p_action = 'mute' then
    update public.room_seats set muted = true, speaking = false where room_id = p_room and user_id = p_user;
    insert into public.room_messages (room_id, user_id, author, kind, body)
    values (p_room, auth.uid(), public.my_display_name(), 'system', target || ' fue silenciado por el anfitrión');
  elsif p_action = 'unmute' then
    update public.room_seats set muted = false, speaking = false where room_id = p_room and user_id = p_user;
    insert into public.room_messages (room_id, user_id, author, kind, body)
    values (p_room, auth.uid(), public.my_display_name(), 'system', target || ' fue activado por el anfitrión');
  elsif p_action = 'kick' then
    delete from public.room_seats where room_id = p_room and user_id = p_user;
    insert into public.room_messages (room_id, user_id, author, kind, body)
    values (p_room, auth.uid(), public.my_display_name(), 'system', target || ' fue expulsado de la sala');
  else
    raise exception 'Acción desconocida';
  end if;
end;
$$;

create or replace function public.leave_seat(p_room uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then raise exception 'Inicia sesión'; end if;
  update public.room_seats set speaking = false where room_id = p_room and user_id = auth.uid();
  delete from public.room_seats where room_id = p_room and user_id = auth.uid();
end;
$$;

grant execute on function public.set_speaking(uuid, boolean) to authenticated;
