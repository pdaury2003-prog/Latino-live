-- A sticker one person throws at another seat. Every phone in the room gets the
-- row the instant it is written and plays the same flight, so the dragon leaves
-- the same seat and lands on the same one everywhere.

create table if not exists public.room_stickers (
  id bigint generated by default as identity primary key,
  room_id uuid not null references public.rooms (id) on delete cascade,
  sender_id uuid references auth.users (id) on delete set null,
  sender_name text not null default 'Alguien' check (char_length(sender_name) between 1 and 32),
  from_seat integer check (from_seat is null or from_seat between 1 and 20),
  to_seat integer check (to_seat is null or to_seat between 1 and 20),
  sticker_id text not null check (char_length(sticker_id) between 1 and 40),
  created_at timestamptz not null default now()
);

create index if not exists room_stickers_room_created_idx
  on public.room_stickers (room_id, created_at desc);

alter table public.room_stickers enable row level security;

drop policy if exists room_stickers_read on public.room_stickers;
create policy room_stickers_read on public.room_stickers
  for select to authenticated using (true);

drop policy if exists room_stickers_send on public.room_stickers;
create policy room_stickers_send on public.room_stickers
  for insert to authenticated with check (sender_id = auth.uid());

-- Stickers live seconds; old rows would otherwise pile up with every gift and
-- message the room already keeps.
create or replace function public.trim_room_stickers()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  delete from public.room_stickers where created_at < now() - interval '1 hour';
  return new;
end;
$$;

drop trigger if exists room_stickers_trim on public.room_stickers;
create trigger room_stickers_trim
  before insert on public.room_stickers
  for each row execute function public.trim_room_stickers();

do $$
begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'room_stickers'
  ) then
    alter publication supabase_realtime add table public.room_stickers;
  end if;
end;
$$;
