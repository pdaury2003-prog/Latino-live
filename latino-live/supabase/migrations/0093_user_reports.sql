-- Denuncias de personas: cualquiera con cuenta puede denunciar a otra por su
-- comportamiento en la app. La denuncia queda guardada, el equipo la ve en el
-- panel del dueno y puede darla por revisada. Nadie ve quien denuncio salvo el
-- equipo, y una persona no puede denunciar dos veces por lo mismo el mismo dia.

create table if not exists public.profile_reports (
  id bigint generated by default as identity primary key,
  reporter_id uuid not null references auth.users (id) on delete cascade,
  target_id uuid not null references auth.users (id) on delete cascade,
  reason text not null check (reason in ('adult', 'harass', 'spam', 'impersonate', 'fraud', 'other')),
  detail text,
  room_id uuid references public.rooms (id) on delete set null,
  created_at timestamptz not null default now(),
  reviewed_at timestamptz,
  reviewed_by uuid references auth.users (id) on delete set null,
  check (reporter_id <> target_id)
);

create index if not exists profile_reports_open on public.profile_reports (created_at desc) where reviewed_at is null;
create index if not exists profile_reports_target on public.profile_reports (target_id, created_at desc);

alter table public.profile_reports enable row level security;

-- Nadie lee ni escribe la tabla directamente: todo pasa por las funciones de
-- abajo, que comprueban quien denuncia y quien revisa.
revoke all on public.profile_reports from public, anon, authenticated;

/** Cualquier cuenta denuncia a otra persona de la app. */
create or replace function public.report_person(p_user uuid, p_reason text, p_detail text default null, p_room uuid default null)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  clean text := nullif(btrim(coalesce(p_detail, '')), '');
  target_name text;
  already integer;
begin
  if uid is null then raise exception 'Inicia sesion para denunciar'; end if;
  if p_user = uid then raise exception 'No puedes denunciarte a ti mismo'; end if;
  if p_reason not in ('adult', 'harass', 'spam', 'impersonate', 'fraud', 'other') then
    raise exception 'Elige un motivo para la denuncia';
  end if;
  if clean is not null and char_length(clean) > 400 then
    raise exception 'La explicacion es demasiado larga';
  end if;
  select display_name into target_name from public.profiles where id = p_user;
  if target_name is null then raise exception 'Esa cuenta no existe'; end if;

  select count(*) into already
    from public.profile_reports r
   where r.reporter_id = uid and r.target_id = p_user
     and r.created_at > now() - interval '1 day';
  if already >= 2 then
    raise exception 'Ya denunciaste a esta persona hoy. El equipo la esta revisando.';
  end if;

  insert into public.profile_reports (reporter_id, target_id, reason, detail, room_id)
  values (uid, p_user, p_reason, clean, p_room);

  perform public.admin_log('report_person', p_user, target_name, 'Denuncia: ' || p_reason);
end;
$$;

revoke all on function public.report_person(uuid, text, text, uuid) from public, anon;
grant execute on function public.report_person(uuid, text, text, uuid) to authenticated;

/** El equipo lee las denuncias, las mas nuevas primero. */
create or replace function public.admin_reports(p_limit integer default 40)
returns table (
  id bigint,
  target_id uuid,
  target_name text,
  target_avatar text,
  reporter_name text,
  reason text,
  detail text,
  created_at timestamptz,
  reviewed_at timestamptz,
  reports_open bigint
)
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  cap integer := greatest(1, least(100, coalesce(p_limit, 40)));
begin
  if not public.is_staff() then raise exception 'No tienes acceso al panel'; end if;
  return query
    select r.id, r.target_id, p.display_name, p.avatar_url,
           coalesce(rep.display_name, 'Alguien'), r.reason, r.detail, r.created_at, r.reviewed_at,
           (select count(*) from public.profile_reports x
             where x.target_id = r.target_id and x.reviewed_at is null
               and x.created_at > now() - interval '30 days')
      from public.profile_reports r
      left join public.profiles p on p.id = r.target_id
      left join public.profiles rep on rep.id = r.reporter_id
     order by (r.reviewed_at is null) desc, r.created_at desc
     limit cap;
end;
$$;

revoke all on function public.admin_reports(integer) from public, anon;
grant execute on function public.admin_reports(integer) to authenticated;

/** El equipo marca una denuncia como revisada. */
create or replace function public.admin_review_report(p_report bigint)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_staff() then raise exception 'No tienes acceso al panel'; end if;
  update public.profile_reports
     set reviewed_at = now(), reviewed_by = auth.uid()
   where id = p_report and reviewed_at is null;
end;
$$;

revoke all on function public.admin_review_report(bigint) from public, anon;
grant execute on function public.admin_review_report(bigint) to authenticated;
