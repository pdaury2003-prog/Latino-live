create table if not exists public.rooms (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique,
  title text not null check (char_length(title) between 1 and 60),
  host_id uuid references auth.users (id) on delete set null,
  host_name text not null default 'Sahar',
  country text not null default 'US' check (country in ('US', 'ES', 'MX', 'AR', 'CO')),
  cover text not null default 'palace' check (cover in ('palace', 'pool', 'terrace')),
  max_seats integer not null default 10 check (max_seats between 4 and 20),
  announcement text not null default '',
  is_official boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.room_seats (
  room_id uuid not null references public.rooms (id) on delete cascade,
  seat_no integer not null check (seat_no between 1 and 20),
  user_id uuid not null references auth.users (id) on delete cascade,
  display_name text not null default 'Invitado',
  avatar_url text,
  muted boolean not null default false,
  joined_at timestamptz not null default now(),
  primary key (room_id, seat_no),
  unique (room_id, user_id)
);

create table if not exists public.room_messages (
  id bigint generated by default as identity primary key,
  room_id uuid not null references public.rooms (id) on delete cascade,
  user_id uuid references auth.users (id) on delete set null,
  author text not null default 'Sala' check (char_length(author) between 1 and 32),
  kind text not null default 'user' check (kind in ('welcome', 'system', 'user', 'announcement', 'gift')),
  body text not null check (char_length(body) between 1 and 400),
  created_at timestamptz not null default now()
);

create index if not exists room_messages_room_created_idx on public.room_messages (room_id, created_at desc, id desc);

create table if not exists public.room_gifts (
  id bigint generated by default as identity primary key,
  room_id uuid not null references public.rooms (id) on delete cascade,
  sender_id uuid references auth.users (id) on delete set null,
  sender_name text not null,
  gift_key text not null references public.gift_catalog (key),
  cost integer not null check (cost > 0),
  created_at timestamptz not null default now()
);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, display_name)
  values (new.id, left(coalesce(nullif(split_part(new.email, '@', 1), ''), 'Invitado'), 32))
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

create or replace function public.trim_room_messages()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  delete from public.room_messages
  where room_id = new.room_id
    and id in (
      select id from public.room_messages
      where room_id = new.room_id
      order by created_at desc, id desc
      offset 20
    );
  return null;
end;
$$;

drop trigger if exists trim_room_messages_after_insert on public.room_messages;
create trigger trim_room_messages_after_insert after insert on public.room_messages
  for each row execute function public.trim_room_messages();

create or replace function public.my_display_name()
returns text
language sql
stable
security definer
set search_path = public
as $$
  select coalesce((select display_name from public.profiles where id = auth.uid()), 'Invitado');
$$;

create or replace function public.open_room(p_title text, p_cover text default 'palace', p_country text default 'US')
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  new_id uuid;
  clean text;
begin
  if uid is null then raise exception 'Inicia sesión para abrir una sala'; end if;
  clean := left(coalesce(nullif(btrim(p_title), ''), 'Mi sala'), 60);
  insert into public.rooms (slug, title, host_id, host_name, country, cover, max_seats)
  values (
    lower(regexp_replace(clean, '[^a-zA-Z0-9]+', '-', 'g')) || '-' || substr(md5(random()::text), 1, 6),
    clean,
    uid,
    public.my_display_name(),
    case when p_country in ('US', 'ES', 'MX', 'AR', 'CO') then p_country else 'US' end,
    case when p_cover in ('palace', 'pool', 'terrace') then p_cover else 'palace' end,
    10
  )
  returning id into new_id;
  insert into public.room_messages (room_id, user_id, author, kind, body)
  values (new_id, uid, public.my_display_name(), 'welcome', 'Bienvenido a la sala. Respeta a los demás. Nada de contenido para adultos, apuestas ni política.');
  return new_id;
end;
$$;

create or replace function public.take_seat(p_room uuid, p_seat integer)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  capacity integer;
  taken uuid;
begin
  if uid is null then raise exception 'Inicia sesión para ocupar un asiento'; end if;
  select max_seats into capacity from public.rooms where id = p_room;
  if capacity is null then raise exception 'La sala ya no existe'; end if;
  if p_seat < 1 or p_seat > capacity then raise exception 'Ese asiento no está disponible'; end if;
  select user_id into taken from public.room_seats where room_id = p_room and seat_no = p_seat;
  if taken is not null and taken <> uid then raise exception 'Ese asiento está ocupado'; end if;
  delete from public.room_seats where room_id = p_room and user_id = uid;
  insert into public.room_seats (room_id, seat_no, user_id, display_name, avatar_url)
  values (p_room, p_seat, uid, public.my_display_name(), (select avatar_url from public.profiles where id = uid))
  on conflict (room_id, seat_no) do update set user_id = excluded.user_id, display_name = excluded.display_name;
end;
$$;

create or replace function public.leave_seat(p_room uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null then raise exception 'Inicia sesión'; end if;
  delete from public.room_seats where room_id = p_room and user_id = auth.uid();
end;
$$;

create or replace function public.post_room_message(p_room uuid, p_body text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  clean text := left(btrim(coalesce(p_body, '')), 400);
begin
  if uid is null then raise exception 'Inicia sesión para escribir'; end if;
  if clean = '' then return; end if;
  if not exists (select 1 from public.rooms where id = p_room) then raise exception 'La sala ya no existe'; end if;
  insert into public.room_messages (room_id, user_id, author, kind, body)
  values (p_room, uid, public.my_display_name(), 'user', clean);
end;
$$;

create or replace function public.room_is_host(p_room uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (select 1 from public.rooms where id = p_room and host_id = auth.uid());
$$;

create or replace function public.expand_room_seats(p_room uuid, p_seats integer)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  next_capacity integer := greatest(4, least(20, p_seats));
begin
  if not public.room_is_host(p_room) then raise exception 'Solo el anfitrión puede cambiar los asientos'; end if;
  update public.rooms set max_seats = next_capacity where id = p_room;
  insert into public.room_messages (room_id, user_id, author, kind, body)
  values (p_room, auth.uid(), public.my_display_name(), 'system', 'El anfitrión amplió la sala a ' || next_capacity || ' asientos');
end;
$$;

create or replace function public.moderate_member(p_room uuid, p_user uuid, p_action text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  target text;
begin
  if not public.room_is_host(p_room) then raise exception 'Solo el anfitrión puede moderar'; end if;
  if p_user = auth.uid() then raise exception 'No puedes moderarte a ti mismo'; end if;
  select display_name into target from public.room_seats where room_id = p_room and user_id = p_user;
  if target is null then raise exception 'Esa persona ya no está en la sala'; end if;
  if p_action = 'mute' then
    update public.room_seats set muted = true where room_id = p_room and user_id = p_user;
    insert into public.room_messages (room_id, user_id, author, kind, body)
    values (p_room, auth.uid(), public.my_display_name(), 'system', target || ' fue silenciado por el anfitrión');
  elsif p_action = 'unmute' then
    update public.room_seats set muted = false where room_id = p_room and user_id = p_user;
    insert into public.room_messages (room_id, user_id, author, kind, body)
    values (p_room, auth.uid(), public.my_display_name(), 'system', target || ' fue activado por el anfitrión');
  elsif p_action = 'kick' then
    delete from public.room_seats where room_id = p_room and user_id = p_user;
    insert into public.room_messages (room_id, user_id, author, kind, body)
    values (p_room, auth.uid(), public.my_display_name(), 'system', target || ' fue expulsado de la sala');
  else
    raise exception 'Acción desconocida';
  end if;
end;
$$;

create or replace function public.set_room_announcement(p_room uuid, p_text text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  clean text := left(btrim(coalesce(p_text, '')), 200);
begin
  if not public.room_is_host(p_room) then raise exception 'Solo el anfitrión puede publicar anuncios'; end if;
  if clean = '' then return; end if;
  update public.rooms set announcement = clean where id = p_room;
  insert into public.room_messages (room_id, user_id, author, kind, body)
  values (p_room, auth.uid(), public.my_display_name(), 'announcement', clean);
end;
$$;

create or replace function public.send_room_gift(p_room uuid, p_gift text)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  gift public.gift_catalog;
  balance integer;
  sender text;
  host uuid;
begin
  if uid is null then raise exception 'Inicia sesión para enviar un regalo'; end if;
  select * into gift from public.gift_catalog where key = p_gift;
  if gift.key is null then raise exception 'Ese regalo no existe'; end if;
  if not exists (select 1 from public.rooms where id = p_room) then raise exception 'La sala ya no existe'; end if;
  update public.profiles set diamonds = diamonds - gift.cost
  where id = uid and diamonds >= gift.cost
  returning diamonds, display_name into balance, sender;
  if balance is null then raise exception 'No tienes suficientes diamantes'; end if;
  select host_id into host from public.rooms where id = p_room;
  if host is not null and host <> uid then
    update public.profiles set gold = gold + floor(gift.cost * 100 * 0.7) where id = host;
  end if;
  insert into public.room_gifts (room_id, sender_id, sender_name, gift_key, cost)
  values (p_room, uid, sender, gift.key, gift.cost);
  insert into public.room_messages (room_id, user_id, author, kind, body)
  values (p_room, uid, sender, 'gift', sender || ' envió ' || gift.name || ' a la sala');
  return balance;
end;
$$;

