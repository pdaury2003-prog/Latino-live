-- Sahar: live voice rooms, shared seats, room chat (latest 20), gifts and host moderation.

create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  display_name text not null default 'Invitado' check (char_length(display_name) between 1 and 32),
  bio text not null default '' check (char_length(bio) <= 200),
  country text not null default 'US' check (country in ('US', 'ES', 'MX', 'AR', 'CO')),
  avatar_url text,
  cover_url text,
  level integer not null default 1 check (level between 1 and 99),
  diamonds integer not null default 30 check (diamonds >= 0),
  gold integer not null default 1200 check (gold >= 0),
  created_at timestamptz not null default now()
);

create table if not exists public.gift_catalog (
  key text primary key,
  name text not null,
  cost integer not null check (cost > 0),
  sort integer not null default 0
);

