-- Moments: a photo and a few words, liked and commented by the community.

create table if not exists public.moments (
  id uuid primary key default gen_random_uuid(),
  author_id uuid not null references auth.users (id) on delete cascade,
  body text not null default '' check (char_length(body) <= 500),
  image_path text,
  room_slug text,
  created_at timestamptz not null default now(),
  check (char_length(body) >= 1 or image_path is not null)
);

create index if not exists moments_created_idx on public.moments (created_at desc);
create index if not exists moments_author_idx on public.moments (author_id, created_at desc);

create table if not exists public.moment_likes (
  moment_id uuid not null references public.moments (id) on delete cascade,
  user_id uuid not null references auth.users (id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (moment_id, user_id)
);

create table if not exists public.moment_comments (
  id bigint generated by default as identity primary key,
  moment_id uuid not null references public.moments (id) on delete cascade,
  user_id uuid not null references auth.users (id) on delete cascade,
  author text not null check (char_length(author) between 1 and 32),
  body text not null check (char_length(body) between 1 and 300),
  created_at timestamptz not null default now()
);

create index if not exists moment_comments_moment_idx on public.moment_comments (moment_id, created_at);

alter table public.moments enable row level security;
alter table public.moment_likes enable row level security;
alter table public.moment_comments enable row level security;

drop policy if exists moments_read on public.moments;
create policy moments_read on public.moments for select to authenticated using (true);
drop policy if exists moments_insert_own on public.moments;
create policy moments_insert_own on public.moments for insert to authenticated with check (author_id = auth.uid());
drop policy if exists moments_delete_own on public.moments;
create policy moments_delete_own on public.moments for delete to authenticated using (author_id = auth.uid());

drop policy if exists moment_likes_read on public.moment_likes;
create policy moment_likes_read on public.moment_likes for select to authenticated using (true);
drop policy if exists moment_likes_insert_own on public.moment_likes;
create policy moment_likes_insert_own on public.moment_likes for insert to authenticated with check (user_id = auth.uid());
drop policy if exists moment_likes_delete_own on public.moment_likes;
create policy moment_likes_delete_own on public.moment_likes for delete to authenticated using (user_id = auth.uid());

drop policy if exists moment_comments_read on public.moment_comments;
create policy moment_comments_read on public.moment_comments for select to authenticated using (true);

-- Photos live under the author's own folder in the public moments bucket.
drop policy if exists moment_photo_read on storage.objects;
create policy moment_photo_read on storage.objects
  for select to authenticated
  using (bucket_id = 'moments');

drop policy if exists moment_photo_insert_own on storage.objects;
create policy moment_photo_insert_own on storage.objects
  for insert to authenticated
  with check (bucket_id = 'moments' and (storage.foldername(name))[1] = auth.uid()::text);

drop policy if exists moment_photo_delete_own on storage.objects;
create policy moment_photo_delete_own on storage.objects
  for delete to authenticated
  using (bucket_id = 'moments' and (storage.foldername(name))[1] = auth.uid()::text);

-- The feed: each moment with its author, counts and whether the reader liked it.
create or replace function public.moment_feed(p_limit integer default 30)
returns table (
  id uuid,
  author_id uuid,
  author text,
  avatar_url text,
  level integer,
  body text,
  image_path text,
  room_slug text,
  created_at timestamptz,
  likes integer,
  comments integer,
  liked boolean
)
language sql
stable
security definer
set search_path = public
as $$
  select m.id, m.author_id, p.display_name, p.avatar_url, p.level, m.body, m.image_path, m.room_slug, m.created_at,
    (select count(*)::int from public.moment_likes l where l.moment_id = m.id),
    (select count(*)::int from public.moment_comments c where c.moment_id = m.id),
    exists (select 1 from public.moment_likes l where l.moment_id = m.id and l.user_id = auth.uid())
  from public.moments m
  join public.profiles p on p.id = m.author_id
  order by m.created_at desc
  limit greatest(1, least(60, coalesce(p_limit, 30)));
$$;

create or replace function public.toggle_moment_like(p_moment uuid)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  liked_now boolean;
begin
  if uid is null then raise exception 'Inicia sesión'; end if;
  if exists (select 1 from public.moment_likes where moment_id = p_moment and user_id = uid) then
    delete from public.moment_likes where moment_id = p_moment and user_id = uid;
    liked_now := false;
  else
    insert into public.moment_likes (moment_id, user_id) values (p_moment, uid);
    liked_now := true;
  end if;
  return liked_now;
end;
$$;

create or replace function public.add_moment_comment(p_moment uuid, p_body text)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  clean text := left(btrim(coalesce(p_body, '')), 300);
  new_id bigint;
begin
  if uid is null then raise exception 'Inicia sesión para comentar'; end if;
  if clean = '' then raise exception 'Escribe un comentario'; end if;
  if not exists (select 1 from public.moments where id = p_moment) then raise exception 'Ese momento ya no existe'; end if;
  insert into public.moment_comments (moment_id, user_id, author, body)
  values (p_moment, uid, public.my_display_name(), clean)
  returning id into new_id;
  return new_id;
end;
$$;

grant execute on function public.moment_feed(integer) to authenticated;
grant execute on function public.toggle_moment_like(uuid) to authenticated;
grant execute on function public.add_moment_comment(uuid, text) to authenticated;

